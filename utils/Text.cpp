int textWidth(const string& text, int scale) {
    if (text.empty()) {
        return 0;
    }
    return static_cast<int>(text.size()) * (glyphWidth + 1) * scale - scale;
}

int textHeight(int scale) {
    return glyphHeight * scale;
}

void drawText(SDL_Renderer* renderer, const string& text, int x, int y, int scale, SDL_Color color) {
    SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, 255);
    int penX = x;
    for (char raw : text) {
        const char c = static_cast<char>(toupper(static_cast<unsigned char>(raw)));
        auto it = glyphs().find(c);
        if (it != glyphs().end()) {
            for (int row = 0; row < glyphHeight; ++row) {
                for (int col = 0; col < glyphWidth; ++col) {
                    if (it->second[row * glyphWidth + col] == '1') {
                        SDL_Rect r{penX + col * scale, y + row * scale, scale, scale};
                        SDL_RenderFillRect(renderer, &r);
                    }
                }
            }
        }
        penX += (glyphWidth + 1) * scale;
    }
}

void drawTextCentered(SDL_Renderer* renderer, const string& text, int centerX, int y, int scale, SDL_Color color) {
    drawText(renderer, text, centerX - textWidth(text, scale) / 2, y, scale, color);
}
